"""OAuth 2.1 configuration file generators."""

from __future__ import annotations

import json

from app.models import AuthConfig, IdentityProvider


class ConfigGenerator:
    """Generates OAuth configuration files (.env, client_secrets.json, oauth.yaml)."""

    def generate_env(self, config: AuthConfig) -> str:
        """Generate .env file content."""
        lines = [
            "# OAuth 2.1 / OpenID Connect Configuration",
            f"APP_NAME={config.app_name}",
            f"OAUTH_PROVIDER={config.provider.value}",
            f"OAUTH_APP_TYPE={config.app_type.value}",
            f"OAUTH_REDIRECT_URI={config.redirect_uri}",
            f"OAUTH_SCOPES={','.join(config.scopes)}",
            f"OAUTH_FLOW={config.flow.value}",
            f"OAUTH_PKCE={'true' if config.pkce else 'false'}",
            f"OAUTH_STACK={config.stack.value}",
            "",
            "# Provider credentials — fill in your own values obtained from the IdP",
            f"{config.provider.value.upper()}_CLIENT_ID=your_client_id",
            f"{config.provider.value.upper()}_CLIENT_SECRET=your_client_secret",
        ]

        if config.custom_issuer:
            lines.append(f"OAUTH_ISSUER={config.custom_issuer}")
        if config.custom_authorization_url:
            lines.append(f"OAUTH_AUTHORIZATION_URL={config.custom_authorization_url}")
        if config.custom_token_url:
            lines.append(f"OAUTH_TOKEN_URL={config.custom_token_url}")
        if config.custom_userinfo_url:
            lines.append(f"OAUTH_USERINFO_URL={config.custom_userinfo_url}")

        lines.append("")
        lines.append("# Generated by Auth-2.1 Constructor")

        return "\n".join(lines) + "\n"

    def generate_client_secrets(self, config: AuthConfig) -> str:
        """Generate client_secrets.json content (Google-style format)."""

        secrets = {
            "installed" if config.app_type in ("spa", "native", "cli") else "web": {
                "client_id": "YOUR_CLIENT_ID",
                "project_id": config.app_name.lower().replace(" ", "-"),
                "auth_uri": config.custom_authorization_url
                or self._default_auth_uri(config.provider),
                "token_uri": config.custom_token_url or self._default_token_uri(config.provider),
                "auth_provider_x509_cert_url": "https://www.googleapis.com/oauth2/v1/certs",
                "client_secret": "YOUR_CLIENT_SECRET",
                "redirect_uris": [config.redirect_uri],
                "javascript_origins": [self._origin_from_uri(config.redirect_uri)],
            }
        }

        return json.dumps(secrets, indent=2, ensure_ascii=False) + "\n"

    def generate_oauth_yaml(self, config: AuthConfig) -> str:
        """Generate oauth.yaml configuration content."""
        lines = [
            "oauth:",
            f"  app_name: {config.app_name}",
            f"  app_type: {config.app_type.value}",
            f"  provider: {config.provider.value}",
            f"  redirect_uri: {config.redirect_uri}",
            f"  flow: {config.flow.value}",
            f"  pkce: {'true' if config.pkce else 'false'}",
            f"  stack: {config.stack.value}",
            "  scopes:",
        ]
        for scope in config.scopes:
            lines.append(f"    - {scope}")

        lines.append("  credentials:")
        lines.append("    client_id: YOUR_CLIENT_ID")
        lines.append("    client_secret: YOUR_CLIENT_SECRET")

        if config.custom_issuer:
            lines.append(f"  issuer: {config.custom_issuer}")
        if config.custom_authorization_url:
            lines.append(f"  authorization_url: {config.custom_authorization_url}")
        if config.custom_token_url:
            lines.append(f"  token_url: {config.custom_token_url}")
        if config.custom_userinfo_url:
            lines.append(f"  userinfo_url: {config.custom_userinfo_url}")

        return "\n".join(lines) + "\n"

    def _default_auth_uri(self, provider: IdentityProvider) -> str:
        defaults = {
            "google": "https://accounts.google.com/o/oauth2/v2/auth",
            "github": "https://github.com/login/oauth/authorize",
            "yandex": "https://oauth.yandex.ru/authorize",
            "vk": "https://oauth.vk.com/authorize",
            "custom_oidc": "https://example.com/oauth2/authorize",
        }
        return defaults.get(provider.value, "https://example.com/oauth2/authorize")

    def _default_token_uri(self, provider: IdentityProvider) -> str:
        defaults = {
            "google": "https://oauth2.googleapis.com/token",
            "github": "https://github.com/login/oauth/access_token",
            "yandex": "https://oauth.yandex.ru/token",
            "vk": "https://oauth.vk.com/access_token",
            "custom_oidc": "https://example.com/oauth2/token",
        }
        return defaults.get(provider.value, "https://example.com/oauth2/token")

    def _origin_from_uri(self, uri: str) -> str:
        """Extract origin (scheme + host + port) from a URI."""
        try:
            scheme, rest = uri.split("://", 1)
            host = rest.split("/", 1)[0]
            return f"{scheme}://{host}"
        except ValueError:
            return uri

    def generate_all(self, config: AuthConfig) -> dict[str, str]:
        """Generate all configuration files.

        Returns:
            Dict mapping filename to file content.
        """
        return {
            ".env": self.generate_env(config),
            "client_secrets.json": self.generate_client_secrets(config),
            "oauth.yaml": self.generate_oauth_yaml(config),
        }
